/**
 * 配置表 7 —— balance.js 全局标定表
 *
 * 为什么需要这张表：
 *   事件表（event.js）里写的是「这个选项值多少钱」，用的是策划好读的整数
 *   （+9 现金、-12 现金、+4 认知）。但一局 14 次抉择累积起来，这些数字会
 *   把属性推爆（实测：不加标定时 84% 的局都是 S 级，现金均值冲到 90+）。
 *
 *   所以再加一层「全局标定系数」，在配置加载时统一施加到所有事件效果和
 *   阶段开销上。好处是：
 *     1. 事件表保持人类可读的数字，不用写 +3.6 这种；
 *     2. 整个经济体的松紧由这一张表控制，改 4 个数字就能重新平衡全局；
 *     3. tools/tune.js 可以直接搜索这 5 个系数，找到最接近目标分布的组合。
 *
 * 这些数值是由 `node tools/tune.js` 网格搜索 108 组 × 3000 局得到的。
 * 重新标定的流程：
 *   1) node tools/tune.js            → 拿到推荐系数
 *   2) 改本文件的 5 个系数
 *   3) node tools/simulate.js --n=20000  → 复核结局品质分布
 *
 * 目标分布：S 8% / A 27% / B 45% / C 20%
 */
(function (g) {
  'use strict';
  var NS = (g.WS = g.WS || {});
  NS.Tables = NS.Tables || {};

  NS.Tables.balance = {
    /** 正向现金收益的系数 */
    cashPos: 0.9,
    /** 负向现金损失的系数（<1 表示手下留情，避免玩家动辄破产） */
    cashNeg: 0.45,
    /** 正向非现金属性收益的系数（属性最容易通胀，压得最狠） */
    otherPos: 0.6,
    /** 负向非现金属性损失的系数 */
    otherNeg: 0.8,
    /** 阶段生活开销系数 */
    upkeep: 0.6,
    /** 缩放后如果变成 0 但原值非 0，至少保留 1，避免出现「无效果」的选项 */
    minAbs: 1
  };
})(typeof globalThis !== 'undefined' ? globalThis : this);
